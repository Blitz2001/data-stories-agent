"""3D renderer: Blender (bpy) builds the chart scene, Pillow draws crisp 2D text on top.

    python render_3d.py --quality draft   # quick look (540x960, 15 fps, few samples)
    python render_3d.py --quality final   # 1080x1920, 30 fps

Engine: EEVEE if a GPU/OpenGL context exists (seconds per frame on a laptop iGPU),
otherwise Cycles on CPU (slower but works anywhere). Everything is generated by
code - no downloaded models, textures or fonts beyond system fonts.
"""
from __future__ import annotations

import argparse
import json
import math
import subprocess
import time
import wave
from pathlib import Path

import bpy
import numpy as np
from mathutils import Vector
from PIL import Image, ImageDraw, ImageFont

import brand as B
from story import build_story, load_population

ROOT = Path(__file__).parent
OUT = ROOT / "out"
FONT_DIR = ROOT / "fonts"   # Inter (SIL Open Font License), bundled so Windows/macOS work too

QUALITY = {
    "draft": dict(scale=0.5, fps=15, samples=6),
    "preview": dict(scale=0.6, fps=24, samples=8),
    "final": dict(scale=1.0, fps=30, samples=10),
}


# ------------------------------------------------------------------ helpers
def srgb_to_linear(hex_color: str, alpha: float = 1.0):
    h = hex_color.lstrip("#")
    rgb = [int(h[i:i + 2], 16) / 255 for i in (0, 2, 4)]
    lin = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in rgb]
    return (*lin, alpha)


def material(name, hex_color, roughness=0.4, emission=0.0, metallic=0.0):
    m = bpy.data.materials.new(name)
    m.use_nodes = True
    bsdf = m.node_tree.nodes["Principled BSDF"]
    col = srgb_to_linear(hex_color)
    bsdf.inputs["Base Color"].default_value = col
    bsdf.inputs["Roughness"].default_value = roughness
    bsdf.inputs["Metallic"].default_value = metallic
    if emission:
        bsdf.inputs["Emission Color"].default_value = col
        bsdf.inputs["Emission Strength"].default_value = emission
    return m


def set_color(mat, hex_color, emission=None):
    bsdf = mat.node_tree.nodes["Principled BSDF"]
    col = srgb_to_linear(hex_color)
    bsdf.inputs["Base Color"].default_value = col
    if emission is not None:
        bsdf.inputs["Emission Color"].default_value = col
        bsdf.inputs["Emission Strength"].default_value = emission


def mix_hex(a: str, b: str, t: float) -> str:
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(pa, pb))


def text_obj(body, size, mat, align="LEFT", font=None):
    cu = bpy.data.curves.new("txt", "FONT")
    cu.body = body
    cu.size = size
    cu.align_x = align
    cu.align_y = "CENTER"
    cu.extrude = 0.02
    if font:
        cu.font = font
    ob = bpy.data.objects.new("txt", cu)
    ob.data.materials.append(mat)
    bpy.context.scene.collection.objects.link(ob)
    BILLBOARDS.append(ob)
    return ob


BILLBOARDS: list = []  # text objects that get a track-to-camera constraint


# ------------------------------------------------------------------ scene
UNIT = 0.20      # scene units per 1 % of population lost
ROW = 1.05       # spacing between bars


def build_scene(story, q):
    bpy.ops.wm.read_factory_settings(use_empty=True)
    sc = bpy.context.scene
    r = sc.render
    r.resolution_x, r.resolution_y = int(B.W * q["scale"]), int(B.H * q["scale"])
    r.resolution_percentage = 100
    r.image_settings.file_format = "PNG"
    r.use_persistent_data = True
    sc.view_settings.view_transform = "Standard"   # keep brand hex colours exact
    sc.view_settings.look = "None"

    world = bpy.data.worlds.new("w")
    world.use_nodes = True  # still required in Blender 5.x
    world.node_tree.nodes["Background"].inputs[0].default_value = srgb_to_linear(B.SURFACE)
    world.node_tree.nodes["Background"].inputs[1].default_value = 1.0
    sc.world = world

    font_reg = bpy.data.fonts.load(str(FONT_DIR / "Inter-Regular.otf"))
    font_bold = bpy.data.fonts.load(str(FONT_DIR / "Inter-Bold.otf"))

    # Floor: dark, slightly glossy so bars get a soft reflection
    bpy.ops.mesh.primitive_plane_add(size=80, location=(0, 0, 0))
    bpy.context.object.data.materials.append(material("floor", "#141413", roughness=0.55))

    # Faint grid lines every 10 %
    grid_mat = material("grid", B.GRID, roughness=0.6, emission=0.6)
    n = len(story["countries"])
    depth = (n - 1) * ROW
    for pct in range(10, 40, 10):
        bpy.ops.mesh.primitive_cube_add(location=(pct * UNIT, depth / 2, 0.005))
        g = bpy.context.object
        g.scale = (0.012, depth / 2 + 0.8, 0.005)
        g.data.materials.append(grid_mat)
        t = text_obj(f"−{pct}%", 0.32, grid_mat, "CENTER", font_reg)
        t.location = (pct * UNIT, -0.95, 0.2)

    text_mat = material("text", B.TEXT, roughness=0.5, emission=0.9)
    value_mat = material("value", B.TEXT_2, roughness=0.5, emission=0.7)

    bars, values = [], []
    for i, (name, label) in enumerate(zip(story["countries"], story["labels"])):
        y = depth - i * ROW           # rank 1 furthest from camera = top of frame
        bpy.ops.mesh.primitive_cube_add(size=1, location=(0, y, 0.3))
        bar = bpy.context.object
        bar.name = f"bar_{name}"
        bevel = bar.modifiers.new("bevel", "BEVEL")
        bevel.width, bevel.segments = 0.06, 3
        bar.data.materials.append(material(f"m_{name}", B.BAR, roughness=0.32, emission=0.15))
        bar["y"] = y
        bars.append(bar)

        lbl = text_obj(label, 0.42, text_mat, "RIGHT", font_reg)
        lbl.location = (-0.35, y, 0.35)
        v = text_obj("", 0.38, value_mat, "LEFT", font_bold)
        v.location = (0.3, y, 0.35)
        values.append(v)

    # Lights: big soft key, cool rim from behind, low fill
    def area(name, loc, energy, size, color="#ffffff"):
        L = bpy.data.lights.new(name, "AREA")
        L.energy, L.size = energy, size
        L.color = srgb_to_linear(color)[:3]
        o = bpy.data.objects.new(name, L)
        o.location = loc
        sc.collection.objects.link(o)
        o.rotation_euler = (Vector((2.5, depth / 2, 0)) - Vector(loc)).to_track_quat("-Z", "Y").to_euler()

    area("key", (-4, -6, 14), 1800, 14)
    area("rim", (3, depth + 10, 9), 700, 10, "#9ec5f4")
    area("fill", (12, -4, 4), 250, 8)

    # Camera aimed at an empty so we can move both freely
    target = bpy.data.objects.new("target", None)
    sc.collection.objects.link(target)
    cam = bpy.data.objects.new("cam", bpy.data.cameras.new("cam"))
    cam.data.lens = 32
    sc.collection.objects.link(cam)
    con = cam.constraints.new("TRACK_TO")
    con.target, con.track_axis, con.up_axis = target, "TRACK_NEGATIVE_Z", "UP_Y"
    sc.camera = cam
    for ob in BILLBOARDS:   # keep labels upright and facing the viewer
        c = ob.constraints.new("DAMPED_TRACK")
        c.target, c.track_axis = cam, "TRACK_Z"
    engine = choose_engine(sc, q)
    return dict(scene=sc, bars=bars, values=values, cam=cam, target=target,
                depth=depth, engine=engine)


EEVEE_PROBE = """
import bpy
bpy.ops.wm.read_factory_settings(use_empty=True)
sc = bpy.context.scene
cam = bpy.data.objects.new("c", bpy.data.cameras.new("c")); sc.collection.objects.link(cam); sc.camera = cam
sc.render.engine = "BLENDER_EEVEE"; sc.render.resolution_x = sc.render.resolution_y = 16
bpy.ops.render.render()
"""


def choose_engine(sc, q) -> str:
    """Use EEVEE when a GPU/OpenGL context exists (fast), else Cycles on CPU.

    The probe runs in a child process because EEVEE without a GPU can abort
    the whole interpreter instead of raising an exception.
    """
    import sys
    r = sc.render
    want = q.get("engine", "auto")
    if want in ("auto", "eevee"):
        try:
            ok = subprocess.run([sys.executable, "-c", EEVEE_PROBE], capture_output=True,
                                timeout=120).returncode == 0
        except subprocess.TimeoutExpired:
            ok = False
        if ok:
            r.engine = "BLENDER_EEVEE"
            sc.eevee.taa_render_samples = 64
            return "eevee"
        if want == "eevee":
            print("EEVEE unavailable (no GPU/OpenGL) - falling back to Cycles CPU")
    r.engine = "CYCLES"
    c = sc.cycles
    c.device, c.samples, c.use_denoising, c.use_adaptive_sampling = "CPU", q["samples"], True, True
    c.max_bounces, c.diffuse_bounces, c.glossy_bounces, c.transmission_bounces = 3, 1, 1, 0
    if want == "cycles-gpu":
        prefs = bpy.context.preferences.addons["cycles"].preferences
        for backend in ("OPTIX", "CUDA"):
            try:
                prefs.compute_device_type = backend
                prefs.get_devices()
                gpus = [d for d in prefs.devices if d.type == backend]
            except TypeError:
                gpus = []
            if gpus:
                for d in prefs.devices:
                    d.use = d.type == backend
                c.device, c.samples = "GPU", max(q["samples"], 64)
                return f"cycles-gpu ({backend})"
        print("No NVIDIA GPU found - using Cycles CPU")
    return "cycles-cpu"


def pose(ctx, story, t):
    """Set bars, labels and camera for time t (seconds)."""
    year = B.year_at(t, story["start"], story["end"])
    vals = B.values_at(story["series"], year, story["start"]) if t >= B.HOOK_END else None
    payoff = B.ease((t - B.RACE_END) / 0.8)
    for i, (c, bar, v) in enumerate(zip(story["countries"], ctx["bars"], ctx["values"])):
        lost = max(-(vals[c]), 0.0) if vals else 0.0
        length = max(lost * UNIT, 0.02)
        bar.scale = (length, 0.72, 0.6)
        bar.location.x = length / 2
        v.data.body = f"−{lost:.0f}%" if vals else ""
        v.location.x = length + 0.3
        mat = bar.data.materials[0]
        if i == 0:   # highlight the leader in the payoff section
            set_color(mat, mix_hex(B.BAR, B.ACCENT, payoff), emission=0.15 + 0.5 * payoff)
        else:
            set_color(mat, mix_hex(B.BAR, "#2a3f5c", payoff * 0.6), emission=0.15)

    d = ctx["depth"]
    # Camera: fly-in during the hook, slow orbit during the race, gentle settle at the end.
    # The chart is framed in the upper-middle of the frame so the bottom stays free
    # for the headline number and captions.
    intro = B.ease(t / B.HOOK_END)
    orbit = math.radians(-12 + 16 * B.ease(t / B.SECONDS))
    dist = 14.0 - 2.0 * intro + 0.6 * payoff
    height = 12.6 - 1.8 * intro + 0.8 * payoff
    cx, cy = 2.2, d / 2 - 3.2 - 0.6 * payoff
    ctx["target"].location = (cx, cy, 0.0)
    ctx["cam"].location = (cx + dist * math.sin(orbit), cy - dist * math.cos(orbit), height)
    return year


# ------------------------------------------------------------------ 2D overlay
def fonts(scale):
    f = lambda name, px: ImageFont.truetype(str(FONT_DIR / name), int(px * scale))
    return dict(brand=f("Inter-Bold.otf", 36), title=f("Inter-Bold.otf", 88),
                sub=f("Inter-Regular.otf", 33), year=f("Inter-Bold.otf", 46),
                cap=f("Inter-Bold.otf", 50), hero=f("Inter-Bold.otf", 170),
                hero_sub=f("Inter-Regular.otf", 42), src=f("Inter-Regular.otf", 26))


def rgba(hex_color, a=1.0):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (int(255 * a),)


def overlay(frame: Image.Image, story, t, year, F, s):
    img = frame.convert("RGBA")
    W, H = img.size
    layer = Image.new("RGBA", img.size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    x0 = int(0.07 * W)

    # Top gradient so text always sits on a calm background
    grad = Image.new("L", (1, H))
    for yy in range(H):
        f = yy / H
        grad.putpixel((0, yy), int(255 * (max(0, 1 - f / 0.24) ** 1.5 * 0.95 + max(0, (f - 0.78) / 0.22) ** 1.5 * 0.9)))
    shade = Image.new("RGBA", img.size, rgba(B.SURFACE))
    shade.putalpha(grad.resize(img.size))
    img = Image.alpha_composite(img, shade)

    d.text((x0, int(0.065 * H)), B.CHANNEL, font=F["brand"], fill=rgba(B.MUTED))
    d.text((W - x0, int(0.065 * H)), f"{int(round(year))}", font=F["year"],
           fill=rgba(B.ACCENT if t >= B.RACE_END else B.TEXT_2), anchor="ra")
    d.text((x0, int(0.095 * H)), story["title"], font=F["title"], fill=rgba(B.TEXT))
    d.text((x0, int(0.155 * H)), story["subtitle"], font=F["sub"], fill=rgba(B.TEXT_2))

    if t < B.HOOK_END + 0.4:
        a = (1 - B.ease((t - B.HOOK_END + 0.1) / 0.5)) * B.ease(t / 0.5)
        dim = 1 - B.ease((t - B.HOOK_END + 0.1) / 0.5)
        d.rectangle((0, int(0.2 * H), W, int(0.76 * H)), fill=rgba(B.SURFACE, 0.82 * dim))
        d.text((W // 2, int(0.42 * H)), f"{story['start']} → {story['end']}", font=F["sub"],
               fill=rgba(B.TEXT_2, a), anchor="mm")
        d.text((W // 2, int(0.47 * H)), "Who got smaller?", font=F["title"],
               fill=rgba(B.TEXT, a), anchor="mm", stroke_width=int(6 * s),
               stroke_fill=rgba(B.SURFACE, a * 0.8))

    if t >= B.RACE_END:
        a = B.ease((t - B.RACE_END) / 0.6)
        shown = story["lead_change"] * B.ease((t - B.RACE_END) / 1.0)  # count-up
        d.text((x0, int(0.745 * H)), f"{shown:.1f}%".replace("-", "−"), font=F["hero"],
               fill=rgba(B.ACCENT, a), anchor="ls")
        d.text((x0, int(0.775 * H)),
               f"{story['lead']}: {story['pop_start']/1e6:.2f}M → {story['pop_end']/1e6:.2f}M people",
               font=F["hero_sub"], fill=rgba(B.TEXT, a))

    for c0, c1, text in B.captions(story):
        if c0 <= t < c1:
            a = B.ease((t - c0) / 0.25)
            box = d.multiline_textbbox((W // 2, int(0.885 * H)), text, font=F["cap"],
                                       anchor="mm", align="center", spacing=int(14 * s))
            pad = int(26 * s)
            d.rounded_rectangle((box[0] - pad, box[1] - pad, box[2] + pad, box[3] + pad),
                                radius=int(22 * s), fill=(0, 0, 0, int(150 * a)))
            d.multiline_text((W // 2, int(0.885 * H)), text, font=F["cap"], anchor="mm",
                             align="center", spacing=int(14 * s), fill=rgba(B.TEXT, a))

    d.text((x0, int(0.965 * H)), f"Source: {story['source_name']}", font=F["src"], fill=rgba(B.MUTED))
    return Image.alpha_composite(img, layer).convert("RGB")


# ------------------------------------------------------------------ music
def write_music(path: Path, seconds: float):
    """Self-generated ambient pad + soft tick (no licensing questions)."""
    sr = 44100
    t = np.linspace(0, seconds, int(sr * seconds), endpoint=False)
    chord = [110.0, 164.81, 220.0, 277.18, 329.63]
    sig = sum(np.sin(2 * np.pi * f * t + 0.3 * np.sin(2 * np.pi * 0.2 * t)) *
              (0.6 + 0.4 * np.sin(2 * np.pi * 0.11 * t + i)) for i, f in enumerate(chord))
    tick = np.sin(2 * np.pi * 1320 * t) * np.exp(-((t * 2) % 1) * 30)
    rise = np.sin(2 * np.pi * (440 + 220 * np.clip((t - 7) / 1, 0, 1)) * t) * np.exp(-np.abs(t - 7.6) * 4)
    sig = sig * 0.1 + 0.05 * tick * (t > B.HOOK_END) * (t < B.RACE_END) + 0.08 * rise
    env = np.minimum(1, t / 0.8) * np.minimum(1, (seconds - t) / 1.2)
    sig = sig * env / np.max(np.abs(sig)) * 0.3
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(sr)
        w.writeframes((sig * 32767).astype(np.int16).tobytes())


# ------------------------------------------------------------------ main
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quality", choices=QUALITY, default="draft")
    ap.add_argument("--engine", choices=["auto", "eevee", "cycles-gpu", "cycles-cpu"], default="auto",
                    help="auto = EEVEE if a GPU is usable, else Cycles CPU. cycles-gpu = best quality on NVIDIA (OptiX)")
    ap.add_argument("--stills", action="store_true", help="only render 3 preview stills")
    args = ap.parse_args()
    q = dict(QUALITY[args.quality], engine=args.engine)

    story = build_story(load_population())
    OUT.mkdir(exist_ok=True)
    (OUT / "story.json").write_text(json.dumps(story, indent=2, ensure_ascii=False))
    ctx = build_scene(story, q)
    print("engine:", ctx["engine"])
    F = fonts(q["scale"])
    tmp = OUT / "_frame.png"
    ctx["scene"].render.filepath = str(tmp)

    def render(t):
        year = pose(ctx, story, t)
        bpy.ops.render.render(write_still=True)
        return overlay(Image.open(tmp), story, t, year, F, q["scale"])

    if args.stills:
        for t in (1.2, 5.0, 9.5):
            render(t).save(OUT / f"3d_still_{t:.1f}s.png")
        return

    fps = q["fps"]
    music = OUT / "music_3d.wav"
    write_music(music, B.SECONDS)
    video = OUT / f"test_clip_3d_{args.quality}.mp4"
    w, h = ctx["scene"].render.resolution_x, ctx["scene"].render.resolution_y
    ff = subprocess.Popen(["ffmpeg", "-y", "-loglevel", "error", "-f", "rawvideo", "-pix_fmt", "rgb24",
                           "-s", f"{w}x{h}", "-r", str(fps), "-i", "-", "-i", str(music),
                           "-vf", f"scale={B.W}:{B.H}:flags=lanczos",
                           "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18",
                           "-c:a", "aac", "-b:a", "160k", "-shortest", "-movflags", "+faststart",
                           str(video)], stdin=subprocess.PIPE)
    n = fps * B.SECONDS
    t0 = time.time()
    for i in range(n):
        ff.stdin.write(render(i / fps).tobytes())
        if i % 10 == 0:
            el = time.time() - t0
            print(f"frame {i}/{n}  {el/(i+1):.1f}s/frame  eta {el/(i+1)*(n-i-1)/60:.1f} min", flush=True)
    ff.stdin.close(); ff.wait()
    print("wrote", video)


if __name__ == "__main__":
    main()
